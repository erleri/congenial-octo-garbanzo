import fs from 'node:fs/promises'
import crypto from 'node:crypto'
import { getDashboardDaily, getDashboardPreviousDaily, getDashboardDailyChange } from '../src/lib/dashboard-price.js'

// A/B use the same immutable projection of the existing dashboard file. No env,
// credentials, provider calls, plan guesses or report-generation calls.
const source = await fs.readFile(new URL('../public/data.json', import.meta.url))
const d = JSON.parse(source)
const currencies = ['BRL', 'MXN', 'CLP', 'COP', 'PEN', 'ARS']
const start = new Date(`${d.baseDate}T00:00:00Z`)
start.setUTCDate(start.getUTCDate() - 89)
const from = start.toISOString().slice(0, 10)
const yearStart = new Date(`${d.baseDate}T00:00:00Z`)
yearStart.setUTCFullYear(yearStart.getUTCFullYear() - 1)
const yearFrom = yearStart.toISOString().slice(0, 10)
const selected = currencies.map(currency => {
  const current = getDashboardDaily(d.dailyRates, currency, d.baseDate)
  const previous = getDashboardPreviousDaily(d.dailyRates, currency, d.baseDate)
  if (!current || !previous || !Number.isFinite(current.value)) throw new Error(`Missing ${currency}`)
  const year = d.dailyRates.filter(r => r.currency === currency && r.rateType === 'LOCAL_PER_USD' && r.date >= yearFrom && r.date <= d.baseDate && Number.isFinite(r.value))
  const monthly = d.monthlyRates.filter(r => r.currency === currency && r.rateType === 'LOCAL_PER_USD' && `${r.year}-${String(r.month).padStart(2, '0')}` <= d.baseDate.slice(0, 7))
    .sort((a,b) => a.year-b.year || a.month-b.month).slice(-24)
  return {
    currency, value: current.value, date: current.date,
    previousDate: previous.date, change: getDashboardDailyChange(current, previous),
    low: Math.min(...year.map(r => r.value)), high: Math.max(...year.map(r => r.value)),
    series: d.dailyRates.filter(r => r.currency === currency && r.rateType === 'LOCAL_PER_USD' && r.date >= from && r.date <= d.baseDate)
      .sort((a,b) => a.date.localeCompare(b.date)).map(r => ({date:r.date, value:r.value, imputed:r.imputationMethod !== 'NONE', status:r.status})),
    monthly: monthly.map(r => ({date:`${r.year}-${String(r.month).padStart(2,'0')}-01`,value:r.value,imputed:r.imputationMethod !== 'NONE',status:r.status})),
  }
})
const usd = d.dailyRates.find(r => r.currency === 'USD' && r.rateType === 'KRW' && r.date === d.baseDate)
const snapshot = {
  version:'ui2-dashboard-comparison/1', source:'public/data.json',
  sourceSha256:crypto.createHash('sha256').update(source).digest('hex'),
  baseDate:d.baseDate, fetchedAt:d.fetchedAt, usdKrw:usd?.value ?? null,
  currencies:selected,
  report:{currency:'CLP',baseDate:'2026-10-09',image:'/artifacts/app-flow-approved-20261030.png',kind:'existing-approved-historical-capture'},
}
await fs.mkdir(new URL('../artifacts/ui2-dashboard/', import.meta.url), {recursive:true})
await fs.writeFile(new URL('../artifacts/ui2-dashboard/snapshot.js', import.meta.url), `// Public stored prices only. Generated by scripts/ui2-dashboard-snapshot.mjs\nwindow.UI2_SNAPSHOT=${JSON.stringify(snapshot).replaceAll('<','\\u003c')};\n`)
console.log(JSON.stringify({baseDate:snapshot.baseDate,currencies:selected.map(r=>r.currency),bytes:JSON.stringify(snapshot).length,sha256:snapshot.sourceSha256}))
