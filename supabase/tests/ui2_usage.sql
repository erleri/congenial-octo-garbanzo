begin;
select no_plan();
select ok(not has_table_privilege('anon','public.app_usage_daily','SELECT'),'anonymous cannot read aggregates');
select ok(not has_table_privilege('authenticated','public.app_usage_daily','INSERT'),'ordinary login cannot forge aggregate rows');
select ok(not has_function_privilege('authenticated','public.record_app_usage(text,text,text,text,text)','EXECUTE'),'signed-in sessions cannot increment anonymous counters');
update app_private.usage_settings set enabled=false,scope='local';
set local role anon;
select is(public.record_app_usage('page_view','dashboard','','','local'),false,'disabled server gate rejects collection');
reset role;
update app_private.usage_settings set enabled=true;
set local role anon;
select is(public.record_app_usage('page_view','dashboard','','','production'),false,'wrong environment cannot pollute local counters');
select is(public.record_app_usage('page_view','dashboard','','','local'),true,'valid public dimension increments');
select throws_ok($$select public.record_app_usage('private_email','dashboard','','','local')$$,'22023','invalid_usage_dimension','arbitrary event is rejected');
select throws_ok($$select public.record_app_usage('report_open','reports','CLP','','local')$$,'22023','public_report_required','draft or missing identity is rejected');
select is(public.record_app_usage('report_open','reports','CLP','not-a-public-report','local'),false,'non-public report cannot be counted');
select throws_ok($$select count(*) from public.app_usage_daily$$,'42501',null,'anon cannot extract readership');
reset role;
insert into public.business_plan_admins(email,active) values('ui2-metrics-admin@example.test',true);
set local role authenticated;
select set_config('request.jwt.claims','{"sub":"33000000-0000-0000-0000-000000000010","email":"ui2-metrics-reader@example.test","role":"authenticated"}',true);
select is((select count(*) from public.app_usage_daily),0::bigint,'ordinary reader sees no metrics');
select set_config('request.jwt.claims','{"sub":"33000000-0000-0000-0000-000000000011","email":"ui2-metrics-admin@example.test","role":"authenticated"}',true);
select ok((select count(*) from public.app_usage_daily)>0,'active administrator can read counters');
reset role;
update public.business_plan_admins set active=false where email='ui2-metrics-admin@example.test';
set local role authenticated;
select is((select count(*) from public.app_usage_daily),0::bigint,'same session loses access immediately when admin revoked');
reset role;
set local role service_role;
select ok((select count(*) from public.app_usage_daily)>0,'service role can inspect aggregates');
reset role;
select * from finish();
rollback;
