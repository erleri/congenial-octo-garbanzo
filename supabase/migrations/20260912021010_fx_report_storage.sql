    v_run.base_date, v_run.id, v_run.schema_version, v_run.generation_mode,
    coalesce(v_run.selected_content ->> 'confidence', v_run.evidence ->> 'confidence', 'low'),
    v_run.selected_content, v_run.evidence, now()
