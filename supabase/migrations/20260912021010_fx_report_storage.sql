create table public.fx_report_runs (
  id uuid primary key default gen_random_uuid(),
  base_date date not null,
  attempt integer not null check (attempt > 0),
  schema_version text not null,
  generation_mode text not null check (generation_mode in ('deterministic', 'ai_enhanced')),
  publish_mode text not null check (publish_mode in ('review', 'automatic')),
  status text not null default 'pending_review'
    check (status in ('pending_review', 'published', 'rejected', 'superseded', 'failed')),
  evidence jsonb not null,
  deterministic_content jsonb not null,
  ai_candidate jsonb,
  selected_content jsonb not null,
  ai_provider text,
  ai_model text,
  raw_ai_response text,
  validation jsonb not null default '{"valid":true,"errors":[]}'::jsonb,
  error_message text,
  created_at timestamptz not null default now(),
  published_at timestamptz,
  unique (base_date, attempt)
);

create table public.fx_report_reviews (
  id bigint generated by default as identity primary key,
  run_id uuid not null references public.fx_report_runs(id),
  decision text not null check (decision in ('approved', 'rejected')),
  reason text check (reason is null or char_length(reason) <= 500),
  reviewed_by_email text not null,
  reviewed_at timestamptz not null default now(),
  unique (run_id)
);

create table public.fx_reports (
  base_date date primary key,
  run_id uuid not null unique references public.fx_report_runs(id),
  schema_version text not null,
  generation_mode text not null check (generation_mode in ('deterministic', 'ai_enhanced')),
  confidence text not null check (confidence in ('high', 'medium', 'low')),
  content jsonb not null,
  evidence jsonb not null,
  published_at timestamptz not null default now()
);

create index fx_report_runs_base_date_created_idx
  on public.fx_report_runs (base_date desc, created_at desc);
create index fx_report_runs_pending_idx
  on public.fx_report_runs (created_at desc)
  where status = 'pending_review';
create index fx_reports_published_idx
  on public.fx_reports (base_date desc, published_at desc);

