create or replace function app_private.review_fx_report(
  p_run_id uuid,
  p_decision text,
  p_reason text default null
)
returns public.fx_report_runs
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_email text := lower((select auth.jwt()) ->> 'email');
  v_run public.fx_report_runs;
begin
  if (select auth.uid()) is null or v_email is null or not (select app_private.is_business_plan_admin()) then
    raise exception 'active administrator access required' using errcode = '42501';
  end if;

  if p_decision not in ('approved', 'rejected') then
    raise exception 'decision must be approved or rejected' using errcode = '22023';
  end if;

  select * into v_run
  from public.fx_report_runs
  where id = p_run_id
  for update;

  if v_run.id is null then
    raise exception 'report run not found' using errcode = 'P0002';
  end if;
  if v_run.status <> 'pending_review' then
    raise exception 'report run is no longer pending review' using errcode = '55000';
  end if;

  insert into public.fx_report_reviews(run_id, decision, reason, reviewed_by_email)
  values (p_run_id, p_decision, nullif(trim(p_reason), ''), v_email);

  if p_decision = 'approved' then
    insert into public.fx_reports(
      base_date, run_id, schema_version, generation_mode, confidence,
      content, evidence, published_at
    ) values (
      v_run.base_date, v_run.id, v_run.schema_version, v_run.generation_mode,
      coalesce(v_run.selected_content ->> 'confidence', v_run.evidence ->> 'confidence', 'low'),
      v_run.selected_content, v_run.evidence, now()
    )
    on conflict (base_date) do update set
      run_id = excluded.run_id,
      schema_version = excluded.schema_version,
      generation_mode = excluded.generation_mode,
      confidence = excluded.confidence,
      content = excluded.content,
      evidence = excluded.evidence,
      published_at = excluded.published_at;

    update public.fx_report_runs
    set status = 'published', published_at = now()
    where id = p_run_id
    returning * into v_run;
  else
    update public.fx_report_runs
    set status = 'rejected'
    where id = p_run_id
    returning * into v_run;
  end if;

  return v_run;
end;
$$;

revoke all on function app_private.review_fx_report(uuid, text, text)
  from public, anon, authenticated;
grant execute on function app_private.review_fx_report(uuid, text, text)
  to authenticated;

